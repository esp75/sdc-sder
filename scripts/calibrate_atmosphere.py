"""Tabulate thermospheric density for the lifetime model in ``sdc.catalogue``.

Uses NRLMSIS 2.1 (Emmert et al. 2021) through the ``pymsis`` package, averaged
over longitude (which spans local time at fixed UT) and latitude, at three
levels of solar and geomagnetic activity. Writes ``src/sdc/data/atmosphere.yaml``
so that the runtime needs no compiled dependency.

    uv run --group research python scripts/calibrate_atmosphere.py
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pymsis
import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "sdc" / "data" / "atmosphere.yaml"

# F10.7 (sfu) and daily Ap for each scenario.
SCENARIOS = {"low": (70.0, 4.0), "moderate": (140.0, 10.0), "high": (220.0, 20.0)}
ALTITUDES = list(range(100, 2001, 10))


def mean_density(f107: float, ap: float) -> list[float]:
    dates = np.array([np.datetime64("2020-03-20T00:00"), np.datetime64("2020-06-21T12:00")])
    lons = np.arange(0, 360, 15)
    lats = np.arange(-80, 81, 10)
    weights = np.cos(np.radians(lats))
    out = pymsis.calculate(
        dates, lons, lats, np.array(ALTITUDES, dtype=float),
        f107s=np.full(len(dates), f107), f107as=np.full(len(dates), f107),
        aps=np.full((len(dates), 7), ap), version=2.1,
    )  # fmt: skip
    rho = out[..., pymsis.Variable.MASS_DENSITY]  # (date, lon, lat, alt), kg/m^3
    by_lat = rho.mean(axis=(0, 1))  # (lat, alt)
    avg = (by_lat * weights[:, None]).sum(axis=0) / weights.sum()
    return [float(f"{v:.4e}") for v in avg]


def main() -> None:
    table = {name: mean_density(f, ap) for name, (f, ap) in SCENARIOS.items()}
    doc = {
        "source": "NRLMSIS 2.1 (model release 2.1 of the NRLMSIS 2.0 model described by Emmert et al. 2021, "
        "doi:10.1029/2020EA001321) via pymsis "
        f"{pymsis.__version__}; mean over longitude and cos-latitude weights at two dates",
        "scenarios": {k: {"f107_sfu": f, "ap": ap} for k, (f, ap) in SCENARIOS.items()},
        "altitude_km": ALTITUDES,
        "density_kg_m3": table,
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    # REUSE-IgnoreStart
    header = (
        "# Generated by scripts/calibrate_atmosphere.py. Do not edit by hand.\n"
        "# SPDX-License-Identifier: Apache-2.0\n"
    )
    # REUSE-IgnoreEnd
    OUT.write_text(header + yaml.safe_dump(doc, sort_keys=False, width=100))
    print("wrote", OUT.relative_to(ROOT))


if __name__ == "__main__":
    main()
