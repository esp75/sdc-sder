"""Write ``src/sder/methodology/research-v0.2.yaml`` from data instead of guesses.

Two tables in method v0.1 were placeholders. This script derives them:

* ``orbital_persistence.lifetime_table``: natural-decay lifetimes from the
  drag model in ``sdc.catalogue`` (NRLMSIS 2.1, moderate solar activity) for
  the median ballistic coefficient of intact payloads in the GCAT snapshot;
* ``environment.bands``: relative spatial density of catalogued objects per
  50 km shell below 2,000 km, from the same snapshot, log-scaled over three
  decades (100 = densest shell).

Everything else is copied from v0.1 unchanged. Run after updating the snapshot:

    uv run python scripts/calibrate_method.py
"""

from __future__ import annotations

import math
import statistics
from pathlib import Path

import yaml

from sdc.catalogue import DRAG_COEFFICIENT, Catalogue, ObjectKind, area_estimate, mass_estimate

ROOT = Path(__file__).resolve().parent.parent
V01 = ROOT / "src" / "sder" / "methodology" / "research-v0.1.yaml"
OUT = ROOT / "src" / "sder" / "methodology" / "research-v0.2.yaml"
ALTITUDES = [200, 250, 300, 350, 400, 450, 500, 550, 600, 650, 700, 750, 800, 900, 1000, 1200, 1500, 2000]
BAND_KM = 50
DECADES = 3
"""Environment score is log-scaled over three decades of density below the densest shell."""


def main() -> None:
    cat = Catalogue.load(ROOT / "data" / "gcat" / "leo-objects.tsv")
    snapshot = yaml.safe_load((ROOT / "data" / "gcat" / "SNAPSHOT.json").read_text())

    ballistic = []
    for o in cat.objects:
        m, a = mass_estimate(o), area_estimate(o)
        if o.kind is ObjectKind.PAYLOAD and m is not None and a is not None and o.diameter_m:
            ballistic.append(DRAG_COEFFICIENT * a.value / m.value)
    b = statistics.median(ballistic)
    table = [[h, float(f"{cat.atmosphere.lifetime_years(h, b, 'moderate'):.3g}")] for h in ALTITUDES]

    env = cat.environment
    per_band = []
    shells_per_band = int(BAND_KM // env.shell_km)
    for start in range(0, 2000, BAND_KM):
        first = int(start // env.shell_km)
        per_band.append((start, sum(env.density[first : first + shells_per_band]) / shells_per_band))
    peak = max(d for _, d in per_band)
    floor = peak / 10**DECADES
    bands = [
        [s, s + BAND_KM, round(max(0.0, 100 * math.log10(max(d, floor) / floor) / DECADES), 1)]
        for s, d in per_band
    ]
    v01 = yaml.safe_load(V01.read_text())
    bands += [band for band in v01["environment"]["bands"] if band[0] >= 2000]

    doc = dict(v01)
    doc["id"] = "sder-research-v0.2"
    doc["status"] = "research"
    doc["title"] = "SDER research method v0.2 (persistence and environment calibrated to open data)"
    doc["orbital_persistence"] = {"lifetime_table": table, "saturation_years": 1000}
    doc["environment"] = {"bands": bands, "default": v01["environment"]["default"]}

    header = f"""# SDER research methodology v0.2. A RESEARCH METHOD, NOT AN OFFICIAL RATING METHOD.
#
# Generated by scripts/calibrate_method.py from the GCAT snapshot of
# {snapshot["currentcat_updated"].removeprefix("Updated ")} (CC BY 4.0, J. C. McDowell) and NRLMSIS 2.1.
# Do not edit by hand.
#
# What changed from v0.1 (see papers/wp-04-catalogue/README.md):
# - orbital_persistence.lifetime_table: drag-decay lifetimes (sdc.catalogue,
#   moderate solar activity, F10.7 = 140) for the median intact payload in the
#   snapshot, Cd*A/m = {b:.4f} m^2/kg. The model was backtested on reentered
#   rocket bodies; see WP-04 section 3.
# - environment.bands: relative spatial density of catalogued objects per 50 km
#   shell below 2,000 km, on a log scale: 100 = densest shell, 0 = a thousand
#   times less dense or emptier. Bands above 2,000 km keep the
#   v0.1 placeholders, because the snapshot covers LEO only.
# Unchanged from v0.1, and still placeholders: weights, evidence widths, band
# thresholds, disposal, conjunction, passivation and maneuverability. The
# consequence term keeps log10(mass): the NASA Standard Breakup Model gives a
# fragment count proportional to M^0.75, so log10 of that count is a linear
# function of log10(M) and ranks objects the same way.
"""
    OUT.write_text(header + "\n" + yaml.safe_dump(doc, sort_keys=False, width=100, default_flow_style=None))
    print("wrote", OUT.relative_to(ROOT), f"(median Cd*A/m {b:.4f} from {len(ballistic)} payloads)")


if __name__ == "__main__":
    main()
