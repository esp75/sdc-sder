"""Write SDER case studies for real objects to ``examples/cases/`` from the GCAT snapshot.

Selection, so the cases span the range of R:
* the highest-R derelict rocket body of each of the eight most common stage
  families among the top 500 derelicts;
* the four highest-R derelict payloads;
* four active payloads: the two highest-R, and the median-R Starlink and OneWeb;
* four small derelict payloads (under 10 kg) near 500 km.

Inputs come only from GCAT. Where GCAT says nothing (passivation, conjunction
screening, and every operator plan for active payloads), the input is left
missing and the engine scores it at worst case, as principle 4 requires.

    uv run python scripts/make_cases.py && uv run python scripts/regenerate.py
"""

from __future__ import annotations

import json
import re
from pathlib import Path

import yaml

from sdc.catalogue import Catalogue, ObjectKind, RankedObject

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "examples" / "cases"


def family(name: str) -> str:
    return re.split(r"\s+(No\.|Stage|\d)", name, maxsplit=1)[0].strip()


def select(cat: Catalogue) -> list[tuple[str, RankedObject]]:
    derelict = [r for r in cat.ranked if not r.obj.active]
    chosen: list[tuple[str, RankedObject]] = []
    families: dict[str, RankedObject] = {}
    for r in derelict[:500]:
        if r.obj.kind is ObjectKind.ROCKET_BODY:
            families.setdefault(family(r.obj.name), r)
    counts = {f: sum(1 for r in derelict[:500] if family(r.obj.name) == f) for f in families}
    for f in sorted(families, key=lambda f: (-counts[f], f))[:8]:
        chosen.append(("derelict rocket body", families[f]))
    payloads = [r for r in derelict if r.obj.kind is ObjectKind.PAYLOAD]
    chosen += [("derelict payload", r) for r in payloads[:4]]
    active = [r for r in cat.ranked if r.obj.active]
    chosen += [("active payload", r) for r in active[:2]]
    for prefix in ("Starlink", "OneWeb"):
        group = [r for r in active if r.obj.name.startswith(prefix)]
        chosen.append(("active payload", group[len(group) // 2]))
    small = [r for r in payloads if (r.obj.mass_kg or 0) < 10 and 450 <= r.obj.mean_altitude_km <= 550]
    chosen += [("small derelict payload", r) for r in small[:: max(1, len(small) // 4)][:4]]
    return chosen


def mission(group: str, r: RankedObject, source: str) -> dict[str, object]:
    o = r.obj
    observed = {"evidence": "independently_observed", "source": source}
    inputs: dict[str, object] = {
        "mean_altitude_km": {"value": round(o.mean_altitude_km, 1), **observed},
        "mass_kg": {
            "value": o.mass_kg,
            "evidence": "modeled" if o.mass_uncertain else "independently_observed",
            "source": source + (" (mass flagged as an estimate)" if o.mass_uncertain else ""),
        },
    }
    if not o.active:
        dead = {"evidence": "independently_observed", "source": source + "; not in the GCAT active list"}
        inputs["disposal_plan"] = {"value": "none", **dead}
        inputs["disposal_reliability"] = {"value": 1.0, **dead}
        inputs["maneuverability"] = {"value": "none", **dead}
    return {
        "mission": {"id": f"gcat-{o.satcat or o.jcat}", "name": f"{o.name} ({group})", "operator": o.owner},
        "inputs": inputs,
    }


def main() -> None:
    cat = Catalogue.load(ROOT / "data" / "gcat" / "leo-objects.tsv")
    snap = json.loads((ROOT / "data" / "gcat" / "SNAPSHOT.json").read_text())
    when = snap["currentcat_updated"].removeprefix("Updated ")
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.yaml"):
        old.unlink()
    for i, (group, r) in enumerate(select(cat), 1):
        source = f"GCAT {when}, {r.obj.jcat}"
        slug = re.sub(r"[^a-z0-9]+", "-", r.obj.name.lower()).strip("-")
        path = OUT / f"{i:02d}-{r.obj.satcat or r.obj.jcat}-{slug}.yaml"
        header = (
            "# Generated by scripts/make_cases.py from the GCAT snapshot (CC BY 4.0, J. C. McDowell).\n"
            "# Missing inputs are missing on purpose: GCAT does not record them.\n"
        )
        path.write_text(header + yaml.safe_dump(mission(group, r, source), sort_keys=False, width=100))
        print("wrote", path.relative_to(ROOT))


if __name__ == "__main__":
    main()
